<?php

// Writes the test 8 sales dataset as a PHP file of literal arrays (docs/02 Appendix A).
// Runs once at image build time; generation is never measured. splitmix64 needs
// unsigned 64-bit arithmetic, which PHP ints (signed) don't have, so this uses GMP.
//   php tools/gen-sales.php storage/bench/sales_data.php

const SEED = '0x5EEDBE7C0001';
const COUNT = 50_000;

$mask = gmp_init('0xFFFFFFFFFFFFFFFF');
$state = gmp_init(SEED);

$next = function () use (&$state, $mask): GMP {
    $state = gmp_and($state + gmp_init('0x9E3779B97F4A7C15'), $mask);
    $z = $state;
    $z = gmp_and(gmp_xor($z, $z >> 30) * gmp_init('0xBF58476D1CE4E5B9'), $mask);
    $z = gmp_and(gmp_xor($z, $z >> 27) * gmp_init('0x94D049BB133111EB'), $mask);

    return gmp_xor($z, $z >> 31);
};
$below = fn (int $n): int => gmp_intval(gmp_mod($next(), $n));

$out = fopen($argv[1], 'w');
fwrite($out, "<?php\n\n// Generated by tools/gen-sales.php. [id, region, category, customer_tier, amount_cents, quantity, day]\nreturn [\n");
for ($id = 1; $id <= COUNT; $id++) {
    $region = $below(8);
    $category = $below(50);
    $tier = $below(4);
    $amount = 100 + $below(100_000);
    $quantity = 1 + $below(10);
    $day = $below(365);
    fwrite($out, "[$id,$region,$category,$tier,$amount,$quantity,$day],\n");
}
fwrite($out, "];\n");
fclose($out);
